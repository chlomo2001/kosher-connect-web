#!/usr/bin/env node
// Generates DIASPORA_HOLIDAYS and ISRAEL_HOLIDAYS sets for main.js
// Covers Gregorian years 2020-2125.
// Run: node scripts/generate-holidays.js > /tmp/holidays-out.txt

const { HDate, HebrewCalendar, flags } = require('@hebcal/core');

const GREG_START = 2020;
const GREG_END   = 2125;

// Relevant yom-tov event flags (biblical YT only, not rabbinical):
const YT_FLAGS = flags.YOM_TOV_ENDS | flags.CHAG;

const diaspora = new Set();
const israel   = new Set();

function dateStr(d) {
  return d.toISOString().slice(0, 10);
}

// Iterate over every Jewish year that overlaps [GREG_START, GREG_END]
// A Jewish year starting 1 Tishrei YYYY_heb ≈ Sept/Oct YYYY_greg
// So we need Hebrew years 5780 (≈ 2019) through 5886 (≈ 2125).
const hebrewStart = HDate.fromGregorian(new Date(GREG_START, 0, 1)).year;
const hebrewEnd   = HDate.fromGregorian(new Date(GREG_END, 11, 31)).year + 1;

for (let hy = hebrewStart; hy <= hebrewEnd; hy++) {
  // Diaspora events
  const dEvents = HebrewCalendar.calendar({
    year: hy, isHebrewYear: true,
    il: false, noHolidays: false,
    mask: flags.YOM_TOV_ENDS | flags.CHAG,
  });
  for (const ev of dEvents) {
    const greg = ev.getDate().greg();
    const y = greg.getFullYear();
    if (y < GREG_START || y > GREG_END) continue;
    diaspora.add(greg.toISOString().slice(0, 10));
  }

  // Israel events
  const iEvents = HebrewCalendar.calendar({
    year: hy, isHebrewYear: true,
    il: true, noHolidays: false,
    mask: flags.YOM_TOV_ENDS | flags.CHAG,
  });
  for (const ev of iEvents) {
    const greg = ev.getDate().greg();
    const y = greg.getFullYear();
    if (y < GREG_START || y > GREG_END) continue;
    israel.add(greg.toISOString().slice(0, 10));
  }
}

// Sort for readability
const dArr = [...diaspora].sort();
const iArr = [...israel].sort();

console.log('// Auto-generated by scripts/generate-holidays.js');
console.log('// Covers Gregorian years', GREG_START, '–', GREG_END);
console.log('// Diaspora: 2-day yom tov  |  Israel: 1-day yom tov');
console.log('// Shabbat (Saturday) is handled separately by day-of-week check.');
console.log('');
console.log(`const DIASPORA_HOLIDAYS = new Set([`);

const wrap = (arr) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += 8) {
    lines.push('  ' + arr.slice(i, i + 8).map(d => `'${d}'`).join(','));
  }
  return lines.join(',\n');
};

console.log(wrap(dArr));
console.log(`]);`);
console.log('');
console.log(`const ISRAEL_HOLIDAYS = new Set([`);
console.log(wrap(iArr));
console.log(`]);`);
