// Auto-generates DIASPORA_HOLIDAYS and ISRAEL_HOLIDAYS for main.js
// Run: node scripts/generate-holidays.mjs > scripts/holidays-output.txt
// Covers Gregorian years 2020–2125.

import { HebrewCalendar, flags } from '@hebcal/core';

const GREG_START = 2020;
const GREG_END   = 2125;

// HebrewCalendar.calendar() with mask=CHAG returns major biblical yom tov only.
// flags.CHAG covers: Rosh Hashana, Yom Kippur, Sukkot days 1-2, Shemini Atzeret,
// Simchat Torah, Pesach days 1-2 + 7-8, Shavuot (adjusted for il: true/false).

const diaspora = new Set();
const israel   = new Set();

// One call per Gregorian year; HebrewCalendar handles year boundaries internally.
for (let gy = GREG_START; gy <= GREG_END; gy++) {
  for (const il of [false, true]) {
    const events = HebrewCalendar.calendar({
      year: gy, isHebrewYear: false,
      il,
      mask: flags.CHAG,
    });
    const target = il ? israel : diaspora;
    for (const ev of events) {
      const d = ev.getDate().greg();
      const y = d.getFullYear();
      if (y >= GREG_START && y <= GREG_END) {
        target.add(d.toISOString().slice(0, 10));
      }
    }
  }
}

const dArr = [...diaspora].sort();
const iArr = [...israel].sort();

function format(arr) {
  const lines = [];
  for (let i = 0; i < arr.length; i += 8) {
    lines.push('  ' + arr.slice(i, i + 8).map(d => `'${d}'`).join(','));
  }
  return lines.join(',\n');
}

